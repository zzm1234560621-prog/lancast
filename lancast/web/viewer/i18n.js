let lang = 'en';

function normalizeLang(value) {
  return String(value || '').toLowerCase().indexOf('zh') === 0 ? 'zh' : 'en';
}

export function initI18n(preferred) {
  let detected = preferred;
  if (!detected && typeof navigator !== 'undefined') {
    detected = navigator.language || navigator.userLanguage || 'en';
  }
  lang = normalizeLang(detected);
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }
  return lang;
}

export function getLang() {
  return lang;
}

export function t(key, vars) {
  const dict = DICTS[lang] || DICTS.en;
  let value = dict[key];
  if (value == null) {
    value = DICTS.en[key];
  }
  if (value == null) {
    return key;
  }
  if (vars) {
    value = value.replace(/\{(\w+)\}/g, function (match, name) {
      return vars[name] == null ? match : String(vars[name]);
    });
  }
  return value;
}

/**
 * Fill static markup. Text-only substitution is used deliberately; the only
 * HTML in this project is authored by us and no translation contains markup.
 */
export function applyI18n(root) {
  const scope = root || (typeof document !== 'undefined' ? document : null);
  if (!scope || !scope.querySelectorAll) {
    return;
  }
  const textNodes = scope.querySelectorAll('[data-i18n]');
  for (let i = 0; i < textNodes.length; i += 1) {
    const node = textNodes[i];
    node.textContent = t(node.getAttribute('data-i18n'));
  }
  const placeholders = scope.querySelectorAll('[data-i18n-placeholder]');
  for (let i = 0; i < placeholders.length; i += 1) {
    placeholders[i].setAttribute('placeholder', t(placeholders[i].getAttribute('data-i18n-placeholder')));
  }
  const labels = scope.querySelectorAll('[data-i18n-aria-label]');
  for (let i = 0; i < labels.length; i += 1) {
    labels[i].setAttribute('aria-label', t(labels[i].getAttribute('data-i18n-aria-label')));
  }
  const titles = scope.querySelectorAll('[data-i18n-title]');
  for (let i = 0; i < titles.length; i += 1) {
    titles[i].setAttribute('title', t(titles[i].getAttribute('data-i18n-title')));
  }
}
